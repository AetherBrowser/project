# Code of Conduct

The Servo Project follows the [**Rust Code of Conduct**](https://www.rust-lang.org/policies/code-of-conduct), with the differences below.

Our code of conduct applies to [GitHub repositories](https://github.com/aetherbrowser), and all official Aether Browser venues, rather than the Rust project.

